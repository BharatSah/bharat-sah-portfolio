function SkillCard({ skill, category, index }) {
  const ref = useRef(null)
  const reduceRef = useRef(prefersReducedMotion())

  const handleMove = (e) => {
    const node = ref.current
    if (!node || reduceRef.current) return
    const rect = node.getBoundingClientRect()
    node.style.setProperty('--x', `${e.clientX - rect.left}px`)
    node.style.setProperty('--y', `${e.clientY - rect.top}px`)
  }

  return (
    <Reveal
      delay={index * 80}
      className="group relative"
    >
      <div
        ref={ref}
        onMouseMove={handleMove}
        className="card relative flex h-full flex-col overflow-hidden p-6 transition-all duration-300 hover:-translate-y-1.5 hover:border-paper/40 hover:shadow-[0_24px_60px_-28px_rgba(255,255,255,0.55)]"
      >
        {/* Cursor-following spotlight */}
        <div
          aria-hidden="true"
          className="pointer-events-none absolute inset-0 opacity-0 transition-opacity duration-300 group-hover:opacity-100"
          style={{
            background:
              'radial-gradient(260px circle at var(--x, 50%) var(--y, 0%), rgba(255,255,255,0.14), transparent 60%)',
          }}
        />

        {/* Animated gradient top accent */}
        <span className="absolute inset-x-0 top-0 h-px origin-left scale-x-0 bg-gradient-to-r from-transparent via-paper to-transparent transition-transform duration-500 group-hover:scale-x-100" />

        <span className="label">{category}</span>
        <div className="mt-5 flex flex-1 items-start gap-4">
          <span className="grid h-11 w-11 flex-none items-center justify-center rounded-xl border border-ink-line bg-transparent text-paper transition-all duration-300 group-hover:scale-110 group-hover:border-paper/50 group-hover:shadow-[0_0_30px_-8px_rgba(255,255,255,0.7)]">
            {ICONS[skill.name] || ICONS.JavaScript}
          </span>
          <div>
            <h3 className="font-display text-lg font-semibold text-chalk transition-colors group-hover:text-paper">
              {skill.name}
            </h3>
            <p className="mt-1 text-sm leading-relaxed text-chalk-muted">
              {skill.description}
            </p>
          </div>
        </div>
      </div>
    </Reveal>
  )
}

